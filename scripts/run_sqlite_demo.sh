#!/usr/bin/env bash
set -euo pipefail

# SQLite S1 demo/evidence runner (cargo/binary via scripts/run_gateway.sh).
# Sets durable sqlite_wal defaults and, by default, generates a live demo config
# with the real stdio upstream demo server (e2e/stdio_demo_mcp_server.py) for
# allow/deny/approval/audit evidence flows when no explicit upstream env is set.
# Runtime surfaces remain partial; this script does not claim production readiness.
#
# Usage:
#   ./scripts/run_sqlite_demo.sh
#   SCOPEGATE_CONFIG=./scopegate.toml.example ./scripts/run_sqlite_demo.sh   # use explicit config
#   GATEWAY_MCP_UPSTREAM_URL=http://127.0.0.1:9000/mcp ./scripts/run_sqlite_demo.sh
#   SCOPEGATE_DEMO_STDIO_UPSTREAM=0 ./scripts/run_sqlite_demo.sh             # disable generated stdio demo upstream

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

DATA_DIR="${SCOPEGATE_DEMO_DATA_DIR:-$ROOT/.scopegate}"
DB_PATH="${SCOPEGATE_DEMO_DB_PATH:-$DATA_DIR/scopegate.db}"
DEMO_STDIO="${SCOPEGATE_DEMO_STDIO_UPSTREAM:-1}"
mkdir -p "$DATA_DIR"

normalize_sqlite_db_url() {
  local url="$1"
  [[ -z "$url" ]] && { printf '%s' "$url"; return 0; }
  case "$url" in
    sqlite:*|sqlite://*)
      [[ "$url" == *\?* ]] && { printf '%s' "$url"; return 0; }
      [[ "$url" == *:memory:* || "$url" == "sqlite::memory:" ]] && { printf '%s' "$url"; return 0; }
      printf '%s?mode=rwc' "$url"
      ;;
    *)
      printf '%s' "$url"
      ;;
  esac
}

export GATEWAY_ADDR="${GATEWAY_ADDR:-${SCOPEGATE_BIND_ADDR:-127.0.0.1:8080}}"
export SCOPEGATE_BIND_ADDR="$GATEWAY_ADDR"

# Durable SQLite S1 defaults (env aliases accepted by gateway/config/scripts).
export GATEWAY_STORE_BACKEND="${GATEWAY_STORE_BACKEND:-${SCOPEGATE_STORE_BACKEND:-sqlite_wal}}"
export SCOPEGATE_STORE_BACKEND="${SCOPEGATE_STORE_BACKEND:-$GATEWAY_STORE_BACKEND}"
export GATEWAY_DATABASE_URL="$(normalize_sqlite_db_url "${GATEWAY_DATABASE_URL:-${SCOPEGATE_DATABASE_URL:-sqlite://$DB_PATH}}")"
export SCOPEGATE_DATABASE_URL="${SCOPEGATE_DATABASE_URL:-$GATEWAY_DATABASE_URL}"
export SCOPEGATE_STORE_URL="$(normalize_sqlite_db_url "${SCOPEGATE_STORE_URL:-$SCOPEGATE_DATABASE_URL}")"
export SCOPEGATE_DATABASE_URL="$GATEWAY_DATABASE_URL"

# Optional real upstream wiring passthrough (configure a reachable MCP upstream for pool dispatch):
#   GATEWAY_MCP_UPSTREAM_URL / GATEWAY_MCP_UPSTREAM_CMD / GATEWAY_MCP_UPSTREAM_ARGS / GATEWAY_MCP_UPSTREAM_ID / GATEWAY_MCP_DEFAULT_UPSTREAM

CONFIG_EXPLICIT="${GATEWAY_CONFIG:-${SCOPEGATE_CONFIG:-}}"
if [[ -z "$CONFIG_EXPLICIT" && "$DEMO_STDIO" == "1" && -z "${GATEWAY_MCP_UPSTREAM_URL:-}" && -z "${GATEWAY_MCP_UPSTREAM_CMD:-}" && -f "$ROOT/e2e/stdio_demo_mcp_server.py" ]]; then
  DEMO_CFG="$DATA_DIR/scopegate-sqlite-stdio-demo.generated.toml"
  python3 - "$DEMO_CFG" "$SCOPEGATE_DATABASE_URL" "$SCOPEGATE_STORE_BACKEND" "$SCOPEGATE_BIND_ADDR" "$ROOT" <<'PY'
import os, sys
out, db_url, store_backend, bind_addr, root = sys.argv[1:6]
server = os.path.join(root, "e2e", "stdio_demo_mcp_server.py")
cfg = f'''# Generated by scripts/run_sqlite_demo.sh for sqlite + real stdio upstream demo evidence

[gateway]
fail_closed = true
require_token_scope_for_action = false
egress_policy = "require_approval_on_conflict"
store_backend = "{store_backend or "sqlite_wal"}"
database_url = "{db_url}"
listen_addr = "{bind_addr}"

[mcp]
mode = "http"
default_upstream = "demo-stdio"

[[mcp_upstream]]
id = "demo-stdio"
transport = "stdio"
program = "python3"
args = ["{server}"]

# Minimal demo policy: allow MCP list/health and demo.echo; other tools denied fail-closed.
[[rule]]
principal = "anonymous"
action = "tools/list"
resource = "tools/list"
decision = "permit"

[[rule]]
principal = "anonymous"
action = "tools/call"
resource = "gateway.health"
decision = "permit"

[[rule]]
principal = "anonymous"
action = "tools/call"
resource = "demo.echo"
decision = "permit"

# Keep task API demo path allowed for basic flow coverage.
[[rule]]
principal = "agent"
action = "tool.invoke"
resource = "tool"
decision = "permit"
'''
os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write(cfg)
PY
  export GATEWAY_CONFIG="$DEMO_CFG"
  export SCOPEGATE_CONFIG="$DEMO_CFG"
  echo "[run_sqlite_demo] generated live demo config with sqlite + stdio upstream: $DEMO_CFG"
else
  export GATEWAY_CONFIG="${GATEWAY_CONFIG:-${SCOPEGATE_CONFIG:-$ROOT/scopegate.toml.example}}"
  export SCOPEGATE_CONFIG="$GATEWAY_CONFIG"
fi

echo "[run_sqlite_demo] SQLite S1 preview (best-effort)"
echo "[run_sqlite_demo] config=$GATEWAY_CONFIG addr=$GATEWAY_ADDR"
echo "[run_sqlite_demo] store_backend=$GATEWAY_STORE_BACKEND database_url=$GATEWAY_DATABASE_URL"
if [[ -n "${GATEWAY_MCP_UPSTREAM_URL:-}" || -n "${GATEWAY_MCP_UPSTREAM_CMD:-}" ]]; then
  echo "[run_sqlite_demo] upstream_wiring=env id=${GATEWAY_MCP_UPSTREAM_ID:-<default>} default=${GATEWAY_MCP_DEFAULT_UPSTREAM:-<auto>}"
elif [[ "$DEMO_STDIO" == "1" && -f "$ROOT/e2e/stdio_demo_mcp_server.py" && "$SCOPEGATE_CONFIG" == *"scopegate-sqlite-stdio-demo.generated.toml" ]]; then
  echo "[run_sqlite_demo] upstream_wiring=generated_stdio_demo ($ROOT/e2e/stdio_demo_mcp_server.py)"
else
  echo "[run_sqlite_demo] upstream_wiring=none-configured (set GATEWAY_MCP_UPSTREAM_URL or GATEWAY_MCP_UPSTREAM_CMD, or configure [[mcp_upstream]] in config)"
fi
echo "[run_sqlite_demo] checks: curl -fsS http://$GATEWAY_ADDR/healthz ; curl -fsS http://$GATEWAY_ADDR/readyz"

exec "$ROOT/scripts/run_gateway.sh" "$@"
